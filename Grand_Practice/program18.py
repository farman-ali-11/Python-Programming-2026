# Function with arguments

def fr(name, greeting="Best of luck.."):
    print(f"Hello, {name}")
    print(greeting)

fr("Farman Rajper", "You are the best..")
fr("Ahmed Khan")


def rf():
    print("Good Day")

rf()

def fun(name="Khan_Sahb"):
    print("Good Evening")
    print(f"Hey.. {name}")

fun("Rajper_Sahb")
fun()